// generate-schema-stamp.mjs — writes src/generated/schemaStamp.ts from
// @tokenlighten/mcp-server's actual, currently-built advertised tool
// surface, BEFORE esbuild.config.mjs bundles extension.ts.
//
// Why this exists (VS Code MCP definition-cache mitigation, v0.13.0): VS
// Code persistently caches the tool list it receives from a registered MCP
// server definition, keyed by that definition's identity — real-machine
// reproduction showed a tool schema that fails VS Code's own client-side
// validation can wedge that cache so hard that neither a window reload nor
// an extension reinstall recovers it (only re-registering under a brand-new
// definition identity did). mcpProvider.ts's McpStdioServerDefinition sets
// its `version` field from TOKENLIGHTEN_SCHEMA_STAMP (an official, stable
// VS Code API contract: "If this changes, the editor will indicate that
// tools have changed and prompt to refresh them" — @types/vscode's
// McpStdioServerDefinition.version doc comment) so a genuine schema change
// is visible to VS Code as a genuine definition change, without depending on
// the extension's own package.json version alone (which real-machine testing
// showed was not sufficient by itself to recover an already-wedged cache).
//
// Run order: this script must run BEFORE esbuild.config.mjs, since
// mcpProvider.ts imports the file this script writes as an ordinary static
// TypeScript module — see package.json's "build" script. It runs AFTER the
// root `npm run build` has already built every workspace package in
// dependency order (see the root package.json's own "build" script), so
// packages/mcp-server/dist/index.js — a plain `tsc` build, not an
// esbuild bundle — already exists by the time this script runs.
//
// Why dist/index.js (the plain tsc library build) rather than the
// esbuild-bundled dist/node_modules/@tokenlighten/mcp-server/dist/bin.js that
// scripts/bundle-cli.mjs later produces for the shipped VSIX: bundle-cli.mjs
// runs AFTER esbuild.config.mjs in vscode:prepublish (`npm --prefix ../..
// run build && npm run bundle-cli`), i.e. strictly after this script would
// need its input to exist — reordering that pipeline just for this stamp
// was judged more invasive than reusing the tsc build already guaranteed
// available at this point. advertisedTools()'s own KILL_SWITCH / experimental
// -protocol branching is unaffected by the choice of which build produced
// the function (neither is active in a plain `node` invocation with no
// special flags/env), so the two computations agree in every real scenario —
// this is a real assertion, not an assumption: schemaStamp.spec.ts's
// bin.js integration-sanity test and this package's own
// test-bundle-cli-setup.mjs both cross-check the two build artifacts'
// stamps against each other.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const EXT_ROOT = join(__dirname, "..");
const REPO_ROOT = join(__dirname, "..", "..", "..");
const MCP_SERVER_INDEX = join(REPO_ROOT, "packages", "mcp-server", "dist", "index.js");
const OUT_DIR = join(EXT_ROOT, "src", "generated");
const OUT_FILE = join(OUT_DIR, "schemaStamp.ts");

async function main() {
  if (!existsSync(MCP_SERVER_INDEX)) {
    throw new Error(
      "generate-schema-stamp: @tokenlighten/mcp-server is not built "
        + `(missing ${MCP_SERVER_INDEX}). Run 'npm run build -w `
        + "@tokenlighten/mcp-server' first (the root `npm run build` already "
        + "does this before building tokenlighten-vscode-extension).",
    );
  }
  const mod = await import(pathToFileURL(MCP_SERVER_INDEX).href);
  if (typeof mod.currentSchemaStamp !== "function") {
    throw new Error(
      "generate-schema-stamp: @tokenlighten/mcp-server does not export "
        + "currentSchemaStamp() — util/schemaStamp.ts / index.ts drifted.",
    );
  }
  const stamp = mod.currentSchemaStamp();
  if (!/^[0-9a-f]{16}$/.test(stamp)) {
    throw new Error(
      `generate-schema-stamp: computed stamp "${stamp}" is not 16 lowercase hex characters`,
    );
  }

  mkdirSync(OUT_DIR, { recursive: true });
  const contents = `\
// GENERATED by scripts/generate-schema-stamp.mjs — do not hand-edit.
// Regenerate with: node scripts/generate-schema-stamp.mjs (run automatically
// by this package's own "build" script, before esbuild.config.mjs).
//
// Deterministic content stamp of @tokenlighten/mcp-server's advertised
// tools/list surface at the time this file was last generated. Committed
// (not gitignored) so a schema change is visible in the SAME diff as the
// code that caused it; src/__tests__/schemaStamp.spec.ts fails CI if this
// committed value ever drifts from what the current source would produce —
// see packages/mcp-server/src/util/schemaStamp.ts for the full rationale.
export const TOKENLIGHTEN_SCHEMA_STAMP = ${JSON.stringify(stamp)};
`;
  writeFileSync(OUT_FILE, contents);
  process.stdout.write(`generate-schema-stamp: ${stamp} -> ${OUT_FILE}\n`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    process.stderr.write(`generate-schema-stamp: ${err instanceof Error ? err.stack ?? err.message : String(err)}\n`);
    process.exit(1);
  });
}
