// question whatever the specific verb is) / "where … is|are
// called|used|invoked|referenced" / "when is|are … called|used|invoked|
// triggered" (the WHEN_CALLERS_VERB_RE exemption from condition, above) /
// "which|who|what … import(s)" (held-out en-24/ja-24: "which modules
// import…"). JA: 呼び出し元/呼び出し箇所/呼び出している箇所/呼んでいる箇所/呼ぶ箇所/使用箇所/
// 使用している箇所/利用箇所/参照箇所/参照元/呼ばれている/呼び出されている/どこから呼ばれ/
// どこで使われ/どの箇所で使用されて/どこで参照されて/どこでアクセスされて/呼び出すのはどこ/
// 呼び出しているのは/依存している/インポートしている.
// ---------------------------------------------------------------------------
// FIX-FACET-R: guard compounds where "call"/"reference"/"import" is used in
// a sense OTHER than a code call-site/usage question -- stripped (see
// detectFacets) before any callers pattern below runs, same technique as
// VALUE_NEGATIVE_GUARDS. held-out2 b-en-31's negative names "call stack" and
// "task queue" together; "reference manual/docs/guide" and an "import
// this/the <file>" DATA-import imperative are brief-listed defensively.
// Round 3 (coordinator category 2): "who/what does X depend on" is the
// SAME do-support direction reversal CALLERS_WHICH_VERB_RE's tempered gap
// already blocks, but CALLERS_PHRASE_EN_RE's bare `depends?\s+on` below has
// no determiner requirement at all -- it fires on the literal substring
// regardless of surrounding words, so it was never protected. Guarded here
// (the flagged residual from this module's own round-2 report) rather than
// making the bare phrase itself direction-aware, since the bare phrase's
// correct-direction uses ("which components depend on X") never contain a
// do-support aux between the determiner and "depend".
const CALLERS_DO_SUPPORT_DEPEND_GUARD_RE = /\b(?:what|who|which|when)\s+(?:does|do|did)\b[^.?!]{0,40}?\bdepends?\s+on\b/gi;
// held-out4 d-ja-37: JA marks DIRECTION with the particle, not word order --
// 「Xが import してる/参照してる/呼び出してる/使ってる/依存してる」(X marked by が/は,
// the SUBJECT of the verb) asks for X's OWN dependencies, the JA mirror of
// the do-support guard above; 「Xを import している」(X marked by を, the
// OBJECT) is the correct callers direction and stays unguarded -- the
// pattern anchors on が/は immediately (within a short gap) preceding the
// verb root, never on を.
const CALLERS_NEGATIVE_GUARDS: readonly RegExp[] = [
  /\bcall\s+stacks?\b/gi,
  /\btask\s+queues?\b/gi,
  /\breference\s+(?:manuals?|docs?|guides?)\b/gi,
  /\bimports?(?:ing|ed)?\s+(?:this|the)\s+(?:file|data|spreadsheet|csv|dataset|document)\b/gi,
  CALLERS_DO_SUPPORT_DEPEND_GUARD_RE,
  /(?:が|は)[^、。]{0,6}(?:import|参照|呼び出し|使用|使っ|依存)\s*(?:して|してる|している)/gi,
];
const CALLERS_PHRASE_EN_RE = /\bcallers?\b|\bcall\s*sites?\b|\busages?\b|\breferences?\s+to\b|\bdependents?\b|\bcalled\s+(?:by|from)\b|\binvoked\s+(?:by|from)\b|\bused\s+(?:by|from)\b|\breferenced\s+(?:by|from)\b|\bdepends?\s+on\b/i;
// held-out2 b-en-04: "who ACTUALLY invokes" -- an -ly adverb (actually,
// really, currently, ...) between "who" and its verb is ordinary English
// adverb placement, not a new verb of its own; allowing exactly one general
// -ly-adverb slot keeps the match anchored to "who <verb>s" while covering
// the adverb-inserted form. Round 2 (coordinator review): the candidate
// "verb" must not itself be does/is/was/has -- those end in s/es too, but
// "who DOES X call?" asks about X's own callees (see CALLERS_WHICH_VERB_RE's
// do-support guard below for the full reasoning), and "who is/was/has ..."
// is a role/possession question, not a call-site one; excluding them stops
// CALLERS_WHO_VERB_RE from matching the auxiliary instead of a real verb.
const CALLERS_WHO_VERB_RE = /\bwho\s+(?:\w+ly\s+)?(?!(?:does|is|was|has)\b)\w*(?:s|es)\b/i;
// FIX-FAB item 8 (eval-0927 review #9, adversarialWhereNoTail): the original
// pattern chained TWO unbounded `[\s\S]*?` spans, so a pathological
// "where is "-repeated input degenerated into catastrophic backtracking
// (measured 44.4 s at 1600 repeats vs 0.5 s before this fix). Bounded to
// fixed-width windows, same style as every other facet regex in this file;
// a clause is already sentence/clause-split before this runs, so a real
// "where ... is/are ... called" question never needs more than a few dozen
// characters either side.
const CALLERS_WHERE_RE = /\bwhere\b(?:[^.?!]){0,60}?\b(?:is|are)\b(?:[^.?!]){0,40}?\b(?:called|used|invoked|referenced|accessed)\b/i;
// held-out2 b-en-11/b-en-23/b-en-24/b-en-06: generalizes the prior
// which/who/what+imports-only check to the full verb frame the brief names
// -- "which <plural noun> call|invoke|use|import|reference|subscribe to|
// consume|depend on" ("every module that subscribes to", "which rendering
// functions reference them") -- "every"/"any" join "which/who/what" as the
// same determiner shape.
//
// Round 2 (coordinator review, direction precision): "what/which ... DOES/DO/
// DID X call/use/import/invoke/reference" is do-support -- X is the SUBJECT
// performing the call, so this asks for X's own callees/dependencies, not
// its callers ("what does OrderService call?" != "which modules call
// OrderService?"). The tempered gap `(?:(?!\b(?:does|do|did)\b)[^.?!])`
// consumes the space between the determiner and the verb ONE character at a
// time and refuses to cross a do/does/did boundary, so a verb reachable only
// by stepping over do-support never matches: "which modules call X" (no
// do-support in the gap) still matches; "what does X call" does not (the
// gap can never step past "does" to reach "call").
const CALLERS_WHICH_VERB_RE =
  /\b(?:which|who|what|every|any)\b((?:(?!\b(?:does|do|did)\b)[^.?!]){0,40}?)\b(?:calls?|invokes?|uses?|imports?|references?|subscribes?\s+to|consumes?|depends?\s+on)\b/i;
// held-out2 b-en-19: "anyone importing|calling|using|invoking|referencing|
// subscribing to|consuming|depending on" -- brief's own "anyone
// <importing|calling|using>" frame ("anyone" is not a which/who/what
// determiner, so it needs its own pattern rather than joining the one
// above).
const CALLERS_ANYONE_RE =
  /\banyone\b[^.?!]{0,40}?\b(?:importing|calling|using|invoking|referencing|subscribing\s+to|consuming|depending\s+on)\b/i;
// held-out3 c-en-07: role nouns "subscribers/listeners/consumers/observers
// (to|of|for) X" name the CALLER'S ROLE directly (a subscriber IS a kind of
// caller/usage site), the general noun-role mirror of the verb "subscribes
// to" above.
// WP-C3 (2026-09-29): the noun alternation is its own constant so the
// descriptor vocabulary below (`isFacetDescriptorTerm`) reads the SAME
// spelling — the regex is unchanged.
const CALLERS_ROLE_NOUNS_EN = "(?:subscribers?|listeners?|consumers?|observers?)";
const CALLERS_ROLE_NOUN_EN_RE = new RegExp(`\\b${CALLERS_ROLE_NOUNS_EN}\\b\\s+(?:to|of|for)\\b`, "i");
// held-out3 c-en-12: "which <plural noun> read(s) X" is the same verb-frame
// shape as CALLERS_WHICH_VERB_RE (same do-support guard, so "what does X
// read" -- X's own reads, not X's readers -- never matches), but "read" is
// far more common in a non-code sense ("read the docs/report/manual") than
// call/use/import/reference are, so it additionally requires the clause to
// name a CODE-SHAPED identifier or a pronoun standing in for one (it/them/
// this/that; JA それ/これ) -- "which teams read the docs" names no code
// identifier and matches no pronoun, so it stays unmatched.
const CALLERS_WHICH_READ_RE = /\b(?:which|who|what|every|any)\b((?:(?!\b(?:does|do|did)\b)[^.?!]){0,40}?)\breads?\b/i;
const CALLERS_READ_OBJECT_PRONOUN_EN_RE = /\breads?\b\s+(?:it|them|this|that)\b/i;
// held-out3 c-ja-12: 読んでいる/読んでる ("is reading") is the JA mirror of
// "which ... read(s) X" above, gated the same way -- それ/これ (it/this) as
// the pronoun object, or a code-shaped identifier elsewhere in the clause.
const CALLERS_READ_JA_RE = /読んでいる|読んでる/;
const PRONOUN_OBJECT_JA_RE = /それ|これ/;

// FIX-FAB item 8 (eval-0927 review #19): "What is the default timeout
// FetchWithRetry uses per attempt?" has no do-support ("does") at all, so
// CALLERS_WHICH_VERB_RE's own do-support guard never engages, and the bare
// "what ... uses" span matched -- a spurious `callers` facet for a value
// question whose real subject (FetchWithRetry) sits BETWEEN the wh-word and
// the verb as a reduced relative clause's own subject ("the default timeout
// [that] FetchWithRetry uses"), not as the wh-word's own head noun. The
// do-support guard's reasoning generalizes past "does"/"do"/"did": whatever
// carries the verb's tense, a SPECIFIC code-shaped identifier sitting
// directly before the verb -- with at least one OTHER word between it and
// the wh-word (an inserted OBJECT noun phrase: "is the default TIMEOUT
// `FetchWithRetry` USES") -- names that identifier as the SUBJECT doing the
// calling/using/reading, the reversed direction. A single-word gap ("which
// `OrderService` calls") is left unguarded: there the identifier IS the
// wh-phrase's own immediate head, the same "adjacent to the wh-word" shape
// CALLERS_WHO_VERB_RE already accepts unconditionally.
function isCodeShapedWord(token: string): boolean {
  if (token.length < 2) return false;
  if (token.includes("_") || token.includes("$")) return true;
  if (isPascalCaseHump(token)) return true;
  if (/^[a-z][A-Za-z0-9]*[A-Z]/.test(token)) return true; // camelCase
  return /^[A-Z][A-Z0-9]{2,}$/.test(token) && !isProseAcronym(token); // ALLCAPS, not a prose acronym
}

/** True when `gap` (the captured text between the wh-word and the matched verb) ends in a SUBJECT identifier reached only past an inserted object noun phrase — see the doc comment above. */
function hasReversedSubjectBeforeVerb(gap: string): boolean {
  const words = gap.trim().split(/\s+/).filter(Boolean);
  return words.length >= 2 && isCodeShapedWord(words[words.length - 1]!);
}

/** `re` must have exactly one capture group: the gap between the wh-word and the verb (CALLERS_WHICH_VERB_RE / CALLERS_WHICH_READ_RE's own shape). */
function matchesInCallersDirection(clause: string, re: RegExp): boolean {
  const match = re.exec(clause);
  return match !== null && !hasReversedSubjectBeforeVerb(match[1] ?? "");
}

function isCallersReadClause(guardedClause: string): boolean {
  const hasEnRead = matchesInCallersDirection(guardedClause, CALLERS_WHICH_READ_RE);
  const hasJaRead = CALLERS_READ_JA_RE.test(guardedClause);
  if (!hasEnRead && !hasJaRead) return false;
  if (CALLERS_READ_OBJECT_PRONOUN_EN_RE.test(guardedClause)) return true;
  if (hasJaRead && PRONOUN_OBJECT_JA_RE.test(guardedClause)) return true;
  return explicitIdentifiersIn(guardedClause).length > 0;
}
