/** Mirrors readCodeTaskPack.ts's (unexported) `isPascalCaseIdentifier`: >=1 internal uppercase "hump" after an initial capital, plus at least one lowercase letter, so a plain capitalized English word ("Explain") never counts. */
function isPascalCaseHump(value: string): boolean {
  if (value.length < 2 || !/^[A-Z]/.test(value)) return false;
  let hasLower = false;
  let hasBoundary = false;
  for (let i = 1; i < value.length; i++) {
    const ch = value[i]!;
    if (/[a-z]/.test(ch)) hasLower = true;
    else if (/[A-Z]/.test(ch)) hasBoundary = true;
    else if (!/[0-9_]/.test(ch)) return false;
  }
  return hasLower && hasBoundary;
}

/**
 * Code-shaped identifiers named verbatim in `clause`: snake_case/CONST_CASE
 * (contains `_`), camelCase/PascalCase (an internal case hump), a bare
 * ALL-CAPS word that is not ordinary prose vocabulary (`isProseAcronym`), or
 * any backtick-quoted token. Mirrors `explicitCodeIdentifiers`'s rules
 * (readCodeTaskPack.ts, not exported — reimplemented here rather than
 * imported, per this module's own no-cross-region-edit constraint) closely
 * enough that V01's English clauses and V03's Japanese clauses name the same
 * identifiers from the same query shape (EN/JA parity — see the held-out
 * spec's V01/V03 parity case).
 */
// P1-7 (eval-0927 review-r3 #7, jaGluedCallers/jaGluedV03): a JA clause with
// no space before its particle glues an ASCII identifier directly onto the
// Japanese that follows ("loadOptionsの呼び出し元", "HTTP_TIMEOUT_MSの既定値") —
// `\p{L}` covers Hiragana/Katakana/Han/Hangul too, so the OLD single-class
// tokenizer below swallowed the particle/suffix into the SAME token as the
// identifier ("loadOptionsの呼び出し元を教えてください", the entire clause minus
// its trailing 。), which is never code-shaped by any test below and so was
// dropped outright — the real identifier was never even a candidate. Fixed
// by tokenizing WESTERN letters (Latin/Greek/Cyrillic — the scripts every
// mainstream language's identifiers are actually written in, plus digits/
// combining marks/connectors/_/$) and CJK letters (Han/Hiragana/Katakana/
// Hangul, plus the katakana long-vowel mark ー) as two DISJOINT token
// classes via a negative lookahead per character, so a run never crosses the
// boundary: "loadOptionsの呼び出し元" now tokenizes to "loadOptions" (western)
// and "の呼び出し元" (CJK) separately, exactly like `salientWords`'s own
// `SALIENT_WORD_RE` (requestItems.ts) already keeps its ASCII and CJK
// alternatives disjoint. A pure-CJK run (計算) or a pure-western run (größe,
// naïve, Ω) is completely unaffected — this only ever inserts a split AT a
// script boundary that used to be glued into one meaningless blob. Applied
// wherever this module tokenizes free text into identifier-shaped words
// (`explicitIdentifiersIn` and `weakSubjectCandidatesIn` below).
const CJK_LETTER_CLASS = "\\p{Script=Han}\\p{Script=Hiragana}\\p{Script=Katakana}\\p{Script=Hangul}ー";
const NON_CJK_ID_START = `(?:(?![${CJK_LETTER_CLASS}])[\\p{L}\\p{Nl}_$])`;
const NON_CJK_ID_CONTINUE = `(?:(?![${CJK_LETTER_CLASS}])[\\p{L}\\p{N}\\p{Mn}\\p{Mc}\\p{Pc}_$])`;
const SCRIPT_AWARE_IDENTIFIER_TOKEN_RE = new RegExp(
  `${NON_CJK_ID_START}${NON_CJK_ID_CONTINUE}*|[${CJK_LETTER_CLASS}]+`,
  "gu",
);

/**
 * Code-shaped identifiers named verbatim in `clause`: snake_case/CONST_CASE
 * (contains `_`), camelCase/PascalCase (an internal case hump), a bare
 * ALL-CAPS word that is not ordinary prose vocabulary (`isProseAcronym`), or
 * any backtick-quoted token. Mirrors `explicitCodeIdentifiers`'s rules
 * (readCodeTaskPack.ts, not exported — reimplemented here rather than
 * imported, per this module's own no-cross-region-edit constraint) closely
 * enough that V01's English clauses and V03's Japanese clauses name the same
 * identifiers from the same query shape (EN/JA parity — see the held-out
 * spec's V01/V03 parity case).
 */
export function explicitIdentifiersIn(clause: string): string[] {
  const cleaned = stripPathSpans("", clause);
  // P1-9 (eval-0927 review-r2 #9, perfEdge): ASCII-only, so a query naming
  // `größe` (whole word, or backtick-quoted) never even reached the
  // `codeShaped` classification below — the ASCII regex split it into
  // meaningless fragments at each non-ASCII letter ("gr", "e"), none of
  // which are code-shaped by themselves, an entirely different failure from
  // a real prose-word rejection. ECMAScript ID_Start/ID_Continue shape, same
  // pattern as callerExpansion/findReferences's own P1-9 fixes; the
  // camelCase/PascalCase-hump and ALL-CAPS classification tests below stay
  // ASCII-cased (a bare lowercase Unicode word, code identifier or ordinary
  // foreign-language prose alike, is genuinely case-indistinguishable
  // either way — no heuristic here decides that).
  const backticked = new Set(
    [...cleaned.matchAll(/`([\p{L}\p{Nl}_$][\p{L}\p{N}\p{Mn}\p{Mc}\p{Pc}_$]*)`/gu)].map((m) => m[1]!.toLowerCase()),
  );
  const tokens = cleaned.match(SCRIPT_AWARE_IDENTIFIER_TOKEN_RE) ?? [];
  const seen = new Set<string>();
  const out: string[] = [];
  for (const token of tokens) {
    const key = token.toLowerCase();
    const codeShaped = token.includes("_")
      || token.includes("$")
      || /^[a-z][A-Za-z0-9]*[A-Z]/.test(token)
      || isPascalCaseHump(token)
      || (/^[A-Z][A-Z0-9]{2,}$/.test(token) && !isProseAcronym(token))
      || backticked.has(key);
    if (!codeShaped) continue;
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(token);
  }
  return out;
}

// Copilot retest r2 (2026-10-02): a name written directly before "(" — the
// same syntactic code signal the computed-value frames already accept as a
// subject (VALUE_COMPUTED_CODE_SUBJECT). A method called on an object
// (`res.json()`, `USER_FIELDS.map()`) is never one: its name is the
// object's, and a same-named workspace function (an `http/json.ts`
// exporting `json`) made itself the focal in review (camelCase and
// `Owner.member` spellings keep their own tiers). "(s)"/"(es)" right after
// a word is an English plural, not a call.
const CALL_SHAPED_NAME_RE = /(?<![\w$.])([A-Za-z_$][\w$]*)\(([^()]*)\)?/g;

/**
 * Names `clause` writes in call syntax, in order, deduplicated
 * case-insensitively: `quote()` -> `quote`, `estimate(cart)` -> `estimate`.
 * `explicitIdentifiersIn` keeps rejecting a plain lowercase word, so without
 * this "calculate exact quote() results for these three carts" named no
 * identifier of its own, inherited the lead sentence's `SAVE500` (a coupon
 * code in the cart data), and resolveFacetFocal's literal tier made the
 * function holding that string (`couponDiscount`) the value focal: quote()'s
 * callees were never served and the pack certified act.answer from 3 of the
 * 9 files the answer needs. Path spans are stripped first, as in
 * `explicitIdentifiersIn`.
 */
export function callShapedNamesIn(clause: string): string[] {
  const cleaned = stripPathSpans("", clause);
  const seen = new Set<string>();
  const out: string[] = [];
  for (const match of cleaned.matchAll(CALL_SHAPED_NAME_RE)) {
    const inner = match[2];
    if (inner !== undefined && match[0].endsWith(")") && /^(?:s|es)$/i.test(inner)) continue;
    const name = match[1]!;
    if (name.length < 2) continue;
    const key = name.toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(name);
  }
  return out;
}

/**
 * P0-1 (eval-0927 review-r3 #1, qualifiedTsMethod/qualifiedTsService/
 * qualifiedPyMethod/tsDecoratorSameLine): a clause naming "A.b" / "A::b" /
 * "A#b" asks about ONE member `b` declared INSIDE the type `A`, not two
 * unrelated identifiers. Plain tokenization above already keeps both halves
 * (a dotted/hashed span is not one identifier-shaped run), but loses the
 * PAIRING — `resolveFacetFocal` (readCodeTaskPack.ts) used to try whichever
 * half happened to be a real declared symbol FIRST, often the class itself,
 * and return it as the focal outright ("Who calls HttpClient.fetchJson?"
 * answered as HttpClient's own callers — its constructor calls — never
 * fetchJson's). Mirrors locateTaskContext.ts's own `extractClassMethodPairs`
 * (same 2-pair cap: a targeted anchor, not a general scan) plus the `::`
 * separator the brief also names; duplicated rather than imported so this
 * module stays fs-free and import-free (the same reasoning
 * `explicitIdentifiersIn` above already gives for reimplementing rather than
 * importing readCodeTaskPack.ts's identifier rules).
 */
export interface QualifiedMemberPair {
  readonly owner: string;
  readonly member: string;
}

const QUALIFIED_MEMBER_RE = /\b([A-Z][A-Za-z0-9_]*)(?:\.|#|::)([a-zA-Z_][A-Za-z0-9_]*)\b/g;

export function qualifiedMemberPairsIn(clause: string): QualifiedMemberPair[] {
  const cleaned = stripPathSpans("", clause);
  const out: QualifiedMemberPair[] = [];
  const re = new RegExp(QUALIFIED_MEMBER_RE.source, "g");
  let m: RegExpExecArray | null;
  while (out.length < 2 && (m = re.exec(cleaned)) !== null) {
    out.push({ owner: m[1]!, member: m[2]! });
  }
  return out;
}

/** A short, purely-grammatical EN stoplist — determiners/aux-verbs/WH-words/imperative-question verbs common to every question shape above, never project or fixture vocabulary (mirrors jaGlossary.ts's own standing rule, applied to English). */
const EN_CONCEPT_STOPWORDS = new Set([
  "the", "and", "for", "are", "was", "were", "what", "which", "who", "how", "under", "when", "does", "did", "that",
  "this", "from", "with", "its", "explain", "describe", "show", "tell", "walk", "trace", "identify", "confirm",
  "check", "through", "there", "have", "you", "we", "does", "not", "any", "all", "each", "into", "onto", "about",
  "conditions", "condition", "callers", "caller", "please", "can", "could", "should", "would", "will",
]);

/** Minimal EN pluralization stemmer — see module doc for the "statuses"/"timeouts"/"retries" worked examples; low-stakes by design (subjectTerms only soft-anchor a concept-based focal resolution, never proof). */
function stemEn(word: string): string {
  if (word.length > 4 && word.endsWith("ies")) return `${word.slice(0, -3)}y`;
  if (word.length > 4 && /(?:s|x|z|ch|sh)es$/.test(word)) return word.slice(0, -2);
  if (word.length > 3 && word.endsWith("s") && !/(?:ss|us|is|as)$/.test(word)) return word.slice(0, -1);
  return word;
}

/**
 * P1-8 (eval-0927 review r2 finding 8, classFlowHandle/classFlowLifecycle):
 * a fixed set of ENGLISH SEQUENCING IDIOMS a flow/order question commonly
 * wraps its real subject in — "step by step", "end-to-end", "in its
 * lifecycle", "in what order", and the question's own "how ... handle(s)"
 * verb construction — name no workspace content of their own; a bare
 * per-word stoplist (`EN_CONCEPT_STOPWORDS` above) cannot exclude them
 * without ALSO suppressing the same words used as genuine domain terms
 * elsewhere ("the payment queue's processing order", "the request
 * handler"). Masked length-preserving (space-fill) so this stays a
 * substring-safe rewrite; mirrors requestItems.ts's own
 * `maskPhrasingIdiomSpans` (a DIFFERENT module scanning DIFFERENT text —
 * request-item topic terms vs facet subjectTerms — so duplicated here
 * rather than adding a cross-module dependency between two otherwise
 * independent pure modules). The "how ... handle(s)" case blanks only the
 * verb, keeping "how" and whatever sits between them (the real subject)
 * untouched, bounded to the same clause so an unrelated later "handle"
 * elsewhere is never touched.
 *
 * P2-14 (eval-0927 review-r3 #14, classFlowLifecycle): "sequence(s)/
 * sequenced" is the SAME question-scaffolding verb as "handle(s)" ("Explain
 * how OrderFlow sequences payment, inventory and shipping" asks the same
 * flow question as "...handles payment and shipping") — left unmasked, its
 * EN stem ("sequence") became a `subjectTerms` entry with no corresponding
 * member anywhere in the focal class, certifying a false
 * `request-item-undetermined:flow` gap ("sequence ... matches no member of
 * OrderFlow") for a class that answered the question completely. Joined to
 * the SAME capture group as `handles?` so both verbs share one masking rule.
 */
const FACET_STEP_BY_STEP_IDIOM_RE = /\bsteps?[\s-]+by[\s-]+step\b/giu;
const FACET_END_TO_END_IDIOM_RE = /\bend[\s-]+to[\s-]+end\b/giu;
const FACET_IN_ITS_LIFECYCLE_IDIOM_RE = /\bin\s+(?:its|their|his|her|the)\s+lifecycle\b/giu;
const FACET_IN_WHAT_ORDER_IDIOM_RE = /\bin\s+what\s+order\b/giu;
const FACET_HOW_X_HANDLES_IDIOM_RE = /\b(how)\b([^.?!]*?)\b(handles?|sequences?|sequenced)\b/giu;

function maskFacetPhrasingIdiomSpans(text: string): string {
  let out = text;
  for (const re of [FACET_STEP_BY_STEP_IDIOM_RE, FACET_END_TO_END_IDIOM_RE, FACET_IN_ITS_LIFECYCLE_IDIOM_RE, FACET_IN_WHAT_ORDER_IDIOM_RE]) {
    out = out.replace(re, (m) => " ".repeat(m.length));
  }
  out = out.replace(FACET_HOW_X_HANDLES_IDIOM_RE, (_m, howWord: string, mid: string, verb: string) => `${howWord}${mid}${" ".repeat(verb.length)}`);
  return out;
}

/** Concept words in `clause`: EN lowercase stems (length >= 3, minus the grammatical stoplist), plus every jaGlossary.ts term that occurs in `clause` as a substring (its stems). Never proof by themselves — see FacetRequirement's own doc. */
export function conceptTermsIn(clause: string): string[] {
  const out = new Set<string>();
  const masked = maskFacetPhrasingIdiomSpans(clause);
  const enWords = masked.toLowerCase().match(/[a-z]{3,}/g) ?? [];
  for (const word of enWords) {
    if (EN_CONCEPT_STOPWORDS.has(word)) continue;
    out.add(stemEn(word));
  }
  for (const [term, stems] of JA_GLOSSARY) {
    if (!clause.includes(term)) continue;
    for (const stem of stems) out.add(stem);
  }
  return [...out];
}

/**
 * P1-8 (eval-0927 review-r3 #8, unicodeCallersTs/cjkCallersEn): "Who calls
 * größe?" / "Who calls 計算?" name their subject in plain prose, not a
 * code-shaped token — a bare lowercase Latin-with-diacritics word or a bare
 * CJK word never satisfies `explicitIdentifiersIn`'s codeShaped test, so it
 * was DROPPED before ever being tried as a focal identifier and the facet
 * fell back to a weak, generic `subjectTerms` concept score (or nothing at
 * all) instead of the real function. This module has no filesystem access
 * (its own fs-free contract), so it can only offer CANDIDATE words, never
 * verify one names a real declaration — the caller (readCodeTaskPack.ts's
 * `resolveFacetFocal`) does that, and per P0-3's identity rule accepts a
 * candidate ONLY on an EXACT declaration match, never as a basis for
 * asserting "empty". Bounded to 4 words per clause (a targeted last resort,
 * tried only once no code-shaped identifier or qualified-member pair
 * resolved anything — see resolveFacetFocal's own doc) — a grammar/facet-
 * keyword word is excluded via the SAME EN_CONCEPT_STOPWORDS list
 * `conceptTermsIn` already screens with, plus the closed set of facet-verb
 * inflections below (call/use/invoke/return/reference/default and their
 * common forms), so "who"/"calls"/"returns" themselves are never spurious
 * lookups; already-explicit (code-shaped) tokens are excluded too, so this
 * only ever adds words `explicitIdentifiersIn` had no way to include.
 */
const FACET_TRIGGER_VERB_STOPWORDS = new Set([
  "call", "calls", "called", "calling", "use", "uses", "used", "using", "invoke", "invokes", "invoked", "invoking",
  "return", "returns", "returned", "returning", "reference", "references", "referenced", "referencing",
  "default", "defaults", "import", "imports", "imported", "importing",
]);

export function weakSubjectCandidatesIn(clause: string, explicitIdentifiers: readonly string[]): string[] {
  const cleaned = stripPathSpans("", clause);
  const masked = maskFacetPhrasingIdiomSpans(cleaned);
  const alreadyExplicit = new Set(explicitIdentifiers.map((id) => id.toLowerCase()));
  const seen = new Set<string>();
  const out: string[] = [];
  for (const token of masked.match(SCRIPT_AWARE_IDENTIFIER_TOKEN_RE) ?? []) {
    if (out.length >= 4) break;
    const key = token.toLowerCase();
    if (seen.has(key) || alreadyExplicit.has(key)) continue;
    seen.add(key);
    const isAsciiOnly = /^[\x00-\x7f]*$/.test(token);
    if (isAsciiOnly && (token.length < 3 || EN_CONCEPT_STOPWORDS.has(key) || FACET_TRIGGER_VERB_STOPWORDS.has(key))) continue;
    out.push(token);
  }
  return out;
}

// ---------------------------------------------------------------------------
// Sentence/clause splitting — backtick-protected (a quoted path/identifier's
// internal punctuation never becomes a split point), and an ASCII sentence
// terminator only splits when followed by whitespace/end (so "reducer.ts."
// splits after the FINAL period, never inside the file extension); a
// Japanese terminator (。！？) always splits (no trailing-space convention in
// Japanese prose).
