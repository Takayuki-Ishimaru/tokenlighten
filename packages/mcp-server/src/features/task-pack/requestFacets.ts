// v0.15.1 runtime review: a clause that only narrows or widens what an
// earlier clause asked for ("including …", "especially …", "in particular …",
// 「…も含めて」). 「…を含む」 is left out: it as often means "containing".
const QUALIFIER_CLAUSE_EN_RE = /^\s*(?:and\s+)?(?:including|includes|incl\.|especially|particularly|in\s+particular|notably|even)\b/i;
const QUALIFIER_CLAUSE_JA_RE = /も含(?:め|む|んで)/u;

function isQualifierClause(clause: string): boolean {
  return QUALIFIER_CLAUSE_EN_RE.test(clause) || QUALIFIER_CLAUSE_JA_RE.test(clause);
}

/**
 * Every (facet, subject) pair `query` asks an answer to show, one entry per
 * (clause, facet) — a clause naming two facets ("limits, who calls it, and
 * the retry rules" is three clauses, but a clause like "the criteria and
 * conditions for X" that matched both `value`-noun and `condition` patterns
 * would contribute two entries) contributes one FacetRequirement per facet.
 *
 * A facet-only clause (no identifier of its own — 既定値, "the callers")
 * inherits the LEAD clause's (the query's first sentence's) identifiers, and
 * UNIONS its own concept terms (if any) with the lead's, so a downstream
 * concept-anchored resolution never loses grounding a clause did carry.
 */
export function extractFacetRequirements(query: string): FacetRequirement[] {
  const trimmed = query.trim();
  if (trimmed.length === 0) return [];
  const sentences = splitSentences(trimmed);
  if (sentences.length === 0) return [];
  const leadIdentifiers = explicitIdentifiersIn(sentences[0]!);
  // v0.15.1 runtime review: a qualifier clause's words ("including same-file
  // …") describe the facet, never the subject, so they are no lead term a
  // facet-only clause inherits.
  const leadSubjectText = splitClauses(sentences[0]!).filter((clause) => !isQualifierClause(clause)).join(" ");
  // 2026-10-24: the scaffolding of an order-of-calls phrasing ("the order it
  // calls …", "in which order") is no subject term (`maskOrderOfCallsCues`) —
  // blanked only in a lead whose own clause carries one, so a lead without it
  // keeps every word; the clause's own is blanked the same way below.
  const leadCues = sentenceCallCues(stripGuardedSpans(sentences[0]!, ALL_NEGATIVE_GUARDS));
  const leadAsksOrderOfCalls = splitClauses(sentences[0]!).some((clause) => isCallOrderClause(stripGuardedSpans(clause, ALL_NEGATIVE_GUARDS), leadCues));
  const leadSubjectSource = leadSubjectText.length > 0 ? leadSubjectText : sentences[0]!;
  const leadTermsSource = leadAsksOrderOfCalls ? maskOrderOfCallsCues(leadSubjectSource) : leadSubjectSource;
  const leadTerms = conceptTermsIn(leadTermsSource);
  const leadQualifiedMembers = qualifiedMemberPairsIn(sentences[0]!);
  const leadCallables = subjectCallableNamesIn(sentences[0]!);

  const requirements: FacetRequirement[] = [];
  for (const sentence of sentences) {
    const sentenceCues = sentenceCallCues(stripGuardedSpans(stripNegatedInstructionParentheticals(sentence), ALL_NEGATIVE_GUARDS));
    for (const clause of splitClauses(sentence)) {
      // P1-10: a negated instruction sitting in its OWN parenthetical inside
      // a larger clause is excised (blanked) here, never used to drop the
      // WHOLE clause -- `declawed` is byte-for-byte `clause` whenever no
      // such parenthetical exists (the overwhelmingly common case), so every
      // other clause shape below is completely unaffected. A clause that
      // reads as a negated instruction (or a change/doc-existence request)
      // even AFTER that excision -- e.g. `splitClauses`'s own comma/"and"
      // split already isolated "please do not modify anything" as its own
      // clause with no parenthetical to strip -- is still dropped exactly as
      // before.
      const declawed = stripNegatedInstructionParentheticals(clause);
      if (isChangeClause(declawed) || isDocumentationExistenceClause(declawed) || isNegatedInstructionClause(declawed)) continue;
      const guardedClause = stripGuardedSpans(declawed, ALL_NEGATIVE_GUARDS);
      const facets = detectFacets(declawed, guardedClause, sentenceCues);
      if (facets.length === 0) continue;
      const identifiers = explicitIdentifiersIn(declawed);
      // v0.15.1 runtime review (2026-10-06): a QUALIFIER clause — "including
      // same-file callers", 「同じファイル内の呼び出し元も含めて」 — names no
      // subject of its own and only refines a facet an earlier clause already
      // asked for. Kept as a facet of its own, its generic words ("including",
      // "same", "file") became the subject: "Explain retry and all of its
      // callers, including same-file callers." bound the second callers facet
      // to `loadProfile` ("pro-FILE") and disclosed a false "0 call sites"
      // gap for it. The earlier requirement already covers the refinement
      // (same-file call sites are served with the callers).
      if (
        identifiers.length === 0
        && isQualifierClause(declawed)
        && !FAILURE_BEHAVIOR_JA_RE.test(declawed)
        && facets.every((facet) => requirements.some((earlier) => earlier.facet === facet))
      ) continue;
      const termsClause = isCallOrderClause(guardedClause, sentenceCues)
        ? maskOrderOfCallsCues(declawed)
        : declawed;
      const ownTerms = conceptTermsIn(termsClause);
      const ownQualifiedMembers = qualifiedMemberPairsIn(declawed);
      const inheritedFromLead = identifiers.length === 0;
      const subjectIdentifiers = inheritedFromLead ? leadIdentifiers : identifiers;
      const subjectTerms = inheritedFromLead ? [...new Set([...ownTerms, ...leadTerms])] : ownTerms;
      const qualifiedMembers = inheritedFromLead ? leadQualifiedMembers : ownQualifiedMembers;
      const ownCallables = subjectCallableNamesIn(declawed);
      const subjectCallables = ownCallables.length > 0 ? ownCallables : inheritedFromLead ? leadCallables : [];
      // P1-8: a weak candidate is never dropped from concept terms either —
      // folded into `subjectTerms` (lowercased, deduped) so a downstream
      // concept-anchored resolution can still use it even where the exact-
      // declaration tier (resolveFacetFocal) does not apply.
      const weakCandidates = weakSubjectCandidatesIn(termsClause, subjectIdentifiers);
      const subjectTermsWithWeak = weakCandidates.length === 0
        ? subjectTerms
        : [...new Set([...subjectTerms, ...weakCandidates.map((w) => w.toLowerCase())])];
      // 2026-10-10 (false flow gaps): which of those words name no point of a
      // flow (see `nonPointTermsIn`) — derived from the same texts the terms
      // came from.
      const nonPointTerms = facets.includes("flow")
        ? nonPointTermsIn(subjectTermsWithWeak, inheritedFromLead ? [termsClause, leadTermsSource] : [termsClause])
        : [];
      for (const facet of facets) {
        requirements.push({
          facet, clause, subjectIdentifiers, subjectTerms: subjectTermsWithWeak, inheritedFromLead,
          qualifiedMembers, subjectWeakCandidates: weakCandidates,
          ...(subjectCallables.length > 0 ? { subjectCallables } : {}),
          ...(facet === "flow" && nonPointTerms.length > 0 ? { nonPointTerms } : {}),
          ...(facet === "flow" ? { subjectTermAliases: conceptAliasGroupsIn(inheritedFromLead ? [termsClause, leadTermsSource] : [termsClause]) } : {}),
        });
      }
    }
  }
  return requirements;
}

// Wording that asks where code is or how pieces of it connect.
const STRUCTURAL_REQUEST_EN_RE = /\b(?:find|locate[sd]?|where|trac(?:e[sd]?|ing)|relations?|relationships?|imports?|imported|references?|referenced|usages?|uses\s+of|used\s+(?:by|in|from)|consum(?:e[sd]?|ers?|ing)|callers?|call(?:s|ed|ing)?|call\s+sites?|connect(?:s|ed|ing|ions?)?|wir(?:e[sd]?|ing)|depend(?:s|ed|ing|ency|encies|ents?)|defined|definitions?|declared|declarations?)\b/iu;
const STRUCTURAL_REQUEST_JA_RE = /どこ|場所|定義|宣言|参照|呼び出|呼ばれ|使われ|使用箇所|利用箇所|関係|関連|接続|依存|インポート|追跡|辿/u;
// Wording that asks what code does or computes, or for a value it uses.
const BEHAVIOUR_REQUEST_EN_RE = /\b(?:explain(?:s|ed|ing)?|explanation|describe[sd]?|description|walk\s+(?:me\s+)?through|calculat(?:e[sd]?|ing|ions?)|comput(?:e[sd]?|ing|ations?)|evaluat(?:e[sd]?|ing|ions?)|returns?|returned|results?|outputs?|values?|constants?|limits?|caps?|thresholds?|defaults?|rates?|maximum|minimum|max|min|behaviou?rs?|behave[sd]?|works?|why|how\s+(?:does|do|did|is|are|was|were|many|much|long|often)|what\s+(?:does|do|did|happens))\b/iu;
const BEHAVIOUR_REQUEST_JA_RE = /説明|解説|計算|算出|求め|挙動|振る舞|振舞|仕組み|動作|処理|いくら|何回|何円|何秒|何件|戻り値|返り値|返す|結果|値|定数|上限|下限|最大|最小|閾値|しきい値|なぜ|どのように|どうやって/u;

/**
 * 2026-10-06 (semantic-frontier bench, after the review's P1-1/P1-2 fix): does
 * the request only LOCATE code or RELATE pieces of it — find / locate / where /
 * trace, the relation, imports, references, usages, callers or dependencies
 * between named code — and ask nothing about what that code does or computes?
 * Such an answer needs no value the code computes with, so the answer
 * dependency closure (readCodeTaskPack.ts `runAnswerDependencyClosure`) adds
 * none: it served the template constant `renderInvoice` reads for "Find
 * InvoiceSchema invoice_schema.gen.ts renderInvoice relation consumed generated
 * schema.", a file the bench's sealed qrels score irrelevant to that question.
 * Any wording about behaviour or values (explain, calculate, what does …
 * return, how many, the constants / limits it uses …) or a value or condition
 * facet makes the request about behaviour, so an ambiguous question keeps the
 * closure: only a clearly structural one goes without it.
 */
export function isStructuralOnlyRequest(query: string): boolean {
  if (!STRUCTURAL_REQUEST_EN_RE.test(query) && !STRUCTURAL_REQUEST_JA_RE.test(query)) return false;
  if (BEHAVIOUR_REQUEST_EN_RE.test(query) || BEHAVIOUR_REQUEST_JA_RE.test(query)) return false;
  return !extractFacetRequirements(query).some((requirement) => requirement.facet === "value" || requirement.facet === "condition");
}
