// Facet order is stable: value, condition, callers, flow — never derived from
// object/Set iteration order, so a caller that reports "the first facet" gets
// a deterministic answer across a Node/engine upgrade.
// ---------------------------------------------------------------------------
const FACET_ORDER: readonly RequestFacet[] = ["value", "condition", "callers", "flow"];

// FIX-FACET-R: every facet's own negative-guard list is stripped together,
// once, before any positive pattern runs -- order-independent (each guard
// only ever blanks its own matched span) and keeps every isXClause function
// working from the SAME guarded text, exactly as before this fix.
const ALL_NEGATIVE_GUARDS: readonly RegExp[] = [
  ...VALUE_NEGATIVE_GUARDS,
  ...TYPE_SHAPE_NEGATIVE_GUARDS,
  ...CONDITION_NEGATIVE_GUARDS,
  ...CALLERS_NEGATIVE_GUARDS,
  ...FLOW_NEGATIVE_GUARDS,
];

function detectFacets(clause: string): RequestFacet[] {
  const guarded = stripGuardedSpans(clause, ALL_NEGATIVE_GUARDS);
  const hits = new Set<RequestFacet>();
  if (isValueClause(guarded)) hits.add("value");
  if (isConditionClause(guarded)) hits.add("condition");
  if (isCallersClause(guarded)) hits.add("callers");
  if (isFlowClause(guarded)) hits.add("flow");
  return FACET_ORDER.filter((facet) => hits.has(facet));
}


