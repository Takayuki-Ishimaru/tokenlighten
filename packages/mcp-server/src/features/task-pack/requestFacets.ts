  /\banyone\b[^.?!]{0,40}?\b(?:importing|calling|using|invoking|referencing|subscribing\s+to|consuming|depending\s+on)\b/i;
// held-out3 c-en-07: role nouns "subscribers/listeners/consumers/observers
// (to|of|for) X" name the CALLER'S ROLE directly (a subscriber IS a kind of
// caller/usage site), the general noun-role mirror of the verb "subscribes
// to" above.
