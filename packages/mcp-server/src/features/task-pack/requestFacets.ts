// value: default(s) / by-default / initial|default value / value(s) [of] /
// limit / threshold / max(imum) / min(imum) / how many / how long /
// constant(s) / configured limit; "which|what" + a value-bearing noun from a
// closed class; "allowed|valid|supported" + a plural noun (held-out en-06/18/
// 26/34/50: "allowed values", "valid error types", "allowed MIME types",
// "valid status codes"). JA: 既定値/デフォルト値/デフォルト/初期値/設定値/上限/下限/
// 最大値/最小値/しきい値/閾値/回数/件数/秒数/定数/いくつ/値, ステータスコード as an object
// noun (brief), 有効な/使用可能な/許可され (JA mirror of allowed/valid/supported —
// the passive-only 許可され, never the imperative 許可して, so "please allow X"
// is not mistaken for a value question).
// ---------------------------------------------------------------------------
const VALUE_NOUN_CLASS = "(?:status\\s+codes?|statuses|codes?|errors?|error\\s+codes?|exceptions?|headers?|options?|flags?|keys?|events?|roles?|permissions?|ports?|levels?|extensions?|values?|settings?|limits?|types?|parameters?|fields?|units?)";
// "constant(s)" is deliberately ABSENT: held-out en-20/ja-20 ("Where is the
// `MAX_UPLOAD_SIZE` constant referenced?" / same in Japanese via 定数) showed
// it fires on "the X constant" used as a mere TYPE-NOUN naming what X is
// (the real ask is `callers`, via "where is X referenced" -- CALLERS_WHERE_RE
// below), not a request for a value. Every other value trigger below still
// covers a genuine "what constant/value" question via `default(s)`/`value(s)`/
// `limit`/`threshold`/etc., so dropping the bare noun costs no held-out recall.
// held-out2 b-en-25: "configured"/"configurable" is a general adjective
// marking ANY setting-shaped noun ("the configured buffer size", "a
// configurable threshold") -- the same role "default(s)"/"limit(s)" already
// play above, generalized past the specific noun that follows.
// held-out3 c-en-17: "upper/lower bound" is a general min/max-value frame,
// the same role "max(imum)/min(imum)" already play above.
const VALUE_BARE_EN_RE = new RegExp(
  `\\bdefaults?\\b|\\bby\\s+default\\b|\\binitial\\s+values?\\b|\\bvalues?\\s+of\\b|\\bvalues?\\b|\\blimits?\\b|\\bthresholds?\\b|\\bmax(?:imum)?\\b|\\bmin(?:imum)?\\b|\\bhow\\s+many\\b|\\bhow\\s+long\\b|\\bconfigured\\b|\\bconfigurable\\b|\\b(?:upper|lower)\\s+bounds?\\b`,
  "i",
);
const VALUE_WHICH_WHAT_RE = new RegExp(`\\b(?:which|what)\\b(?:\\s+\\w+){0,3}?\\s+${VALUE_NOUN_CLASS}\\b`, "i");
// held-out2 b-en-23/b-en-11: the noun after allowed/valid/supported may sit
// behind a HYPHENATED compound modifier ("paper-size constants", "physical
// unit") -- `[\w-]+` generalizes the gap so a hyphen never breaks the match
// (a general English compound-modifier shape, not a rule about paper/DMA/
// etc. nouns); the VALUE_NOUN_CLASS alternative additionally accepts a
// SINGULAR class noun ("allowed physical unit"), not only a bare plural.
const VALUE_ALLOWED_VALID_SUPPORTED_RE = new RegExp(
  `\\b(?:allowed|valid|supported)\\b(?:\\s+[\\w-]+){0,2}?\\s+(?:${VALUE_NOUN_CLASS}|[a-z]+s)\\b`,
  "i",
);
// held-out2 b-en-01/b-en-05/b-en-20: an interrogative "what('s/does) ... set
// to / evaluate to / resolve to / default to / fall back to" asks for a
// concrete configured/computed value -- anchored on the leading "what" so a
// bare imperative ("Set the retry limit to 5 in config.ts") never matches
// (no "what" present at all): a general interrogative frame, not a domain
// noun (brief rule 3's "set X to Y" imperative guard).
// held-out4 d-en-21 (category 5 point 4): the gap must tolerate a
// BACKTICKED PATH containing its own period ("`i18n/loader.py`") without
// treating that period as a sentence terminator -- `[^.?!]` alone stops
// dead at the "." in ".py". A backtick-quoted span is consumed WHOLE (one
// repetition of the gap, regardless of its own length or punctuation),
// exactly like `explicitIdentifiersIn`'s own backtick-aware handling
// elsewhere in this module; a bare non-terminator character is still the
// fallback for everything outside backticks.
const VALUE_SET_OR_RESOLVE_EN_RE =
  /\bwhat(?:'s|\s+is|\s+does)?\b(?:`[^`]*`|[^.?!]){0,40}?\b(?:set\s+to|evaluates?\s+to|resolves?\s+to|defaults?\s+to|falls?\s*back\s+to)\b/i;
// held-out4 d-en-25: "what is/what's THE ... percentage/rate" -- percentage/
// rate as the clause's own ASKED noun. Anchored on "is the"/"'s the"
// directly after "what" (not a bare "which/what ... percentage/rate" scan)
// because "rate"/"percentage" are common enough as part of an UNRELATED
// compound noun elsewhere in a sentence that already contains some other
// "what ..." ("Under what conditions does the RATE limiter block a
