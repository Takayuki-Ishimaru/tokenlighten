const CALLERS_ROLE_NOUNS_EN = "(?:subscribers?|listeners?|consumers?|observers?)";
const CALLERS_ROLE_NOUN_EN_RE = new RegExp(`\\b${CALLERS_ROLE_NOUNS_EN}\\b\\s+(?:to|of|for)\\b`, "i");
// held-out3 c-en-12: "which <plural noun> read(s) X" is the same verb-frame
// shape as CALLERS_WHICH_VERB_RE (same do-support guard, so "what does X
// read" -- X's own reads, not X's readers -- never matches), but "read" is
// far more common in a non-code sense ("read the docs/report/manual") than
// call/use/import/reference are, so it additionally requires the clause to
// name a CODE-SHAPED identifier or a pronoun standing in for one (it/them/
// this/that; JA それ/これ) -- "which teams read the docs" names no code
// identifier and matches no pronoun, so it stays unmatched.
const CALLERS_WHICH_READ_RE = /\b(?:which|who|what|every|any)\b((?:(?!\b(?:does|do|did)\b)[^.?!]){0,40}?)\breads?\b/i;
const CALLERS_READ_OBJECT_PRONOUN_EN_RE = /\breads?\b\s+(?:it|them|this|that)\b/i;
// held-out3 c-ja-12: 読んでいる/読んでる ("is reading") is the JA mirror of
// "which ... read(s) X" above, gated the same way -- それ/これ (it/this) as
// the pronoun object, or a code-shaped identifier elsewhere in the clause.
const CALLERS_READ_JA_RE = /読んでいる|読んでる/;
const PRONOUN_OBJECT_JA_RE = /それ|これ/;

// FIX-FAB item 8 (eval-0927 review #19): "What is the default timeout
// FetchWithRetry uses per attempt?" has no do-support ("does") at all, so
// CALLERS_WHICH_VERB_RE's own do-support guard never engages, and the bare
// "what ... uses" span matched -- a spurious `callers` facet for a value
// question whose real subject (FetchWithRetry) sits BETWEEN the wh-word and
// the verb as a reduced relative clause's own subject ("the default timeout
// [that] FetchWithRetry uses"), not as the wh-word's own head noun. The
// do-support guard's reasoning generalizes past "does"/"do"/"did": whatever
// carries the verb's tense, a SPECIFIC code-shaped identifier sitting
// directly before the verb -- with at least one OTHER word between it and
// the wh-word (an inserted OBJECT noun phrase: "is the default TIMEOUT
// `FetchWithRetry` USES") -- names that identifier as the SUBJECT doing the
// calling/using/reading, the reversed direction. A single-word gap ("which
// `OrderService` calls") is left unguarded: there the identifier IS the
// wh-phrase's own immediate head, the same "adjacent to the wh-word" shape
// CALLERS_WHO_VERB_RE already accepts unconditionally.
function isCodeShapedWord(token: string): boolean {
  if (token.length < 2) return false;
  if (token.includes("_") || token.includes("$")) return true;
  if (isPascalCaseHump(token)) return true;
  if (/^[a-z][A-Za-z0-9]*[A-Z]/.test(token)) return true; // camelCase
  return /^[A-Z][A-Z0-9]{2,}$/.test(token) && !isProseAcronym(token); // ALLCAPS, not a prose acronym
}

/** True when `gap` (the captured text between the wh-word and the matched verb) ends in a SUBJECT identifier reached only past an inserted object noun phrase — see the doc comment above. */
function hasReversedSubjectBeforeVerb(gap: string): boolean {
  const words = gap.trim().split(/\s+/).filter(Boolean);
  return words.length >= 2 && isCodeShapedWord(words[words.length - 1]!);
}

/** `re` must have exactly one capture group: the gap between the wh-word and the verb (CALLERS_WHICH_VERB_RE / CALLERS_WHICH_READ_RE's own shape). */
function matchesInCallersDirection(clause: string, re: RegExp): boolean {
  const match = re.exec(clause);
  return match !== null && !hasReversedSubjectBeforeVerb(match[1] ?? "");
}

function isCallersReadClause(guardedClause: string): boolean {
  const hasEnRead = matchesInCallersDirection(guardedClause, CALLERS_WHICH_READ_RE);
  const hasJaRead = CALLERS_READ_JA_RE.test(guardedClause);
  if (!hasEnRead && !hasJaRead) return false;
  if (CALLERS_READ_OBJECT_PRONOUN_EN_RE.test(guardedClause)) return true;
  if (hasJaRead && PRONOUN_OBJECT_JA_RE.test(guardedClause)) return true;
  return explicitIdentifiersIn(guardedClause).length > 0;
}
