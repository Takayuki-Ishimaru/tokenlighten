// writes it; not tied to any specific screen/module noun.
const CALLERS_IMPORT_JA_MIX_RE = /\bimport\b\s*(?:して|してる|している)/i;
// Additions below (held-out2 b-ja-06/b-ja-16/b-ja-24, brief's own list):
// 参照している/してる, 呼び出している/してる, 購読している/してる, 使っている/使ってる,
// 使用している/してる -- the bare (no 箇所/元 suffix required) progressive form
// of each verb the 箇所-qualified entries above already cover. held-out4
// d-ja-14: 受け取っている/受け取ってる ("is receiving") is the same bare-progressive
// shape for a message/event HANDLER (a receiver IS a kind of caller/usage
// site, the same role subscribe/listen already play). P1-10 (round-4/5
