/** NOT "facet" elsewhere in this codebase — see the module doc's arch-map Q9 note. */
export type RequestFacet = "value" | "condition" | "callers" | "flow";

export interface FacetRequirement {
  readonly facet: RequestFacet;
  /** The query clause it came from — verbatim span (trimmed of surrounding delimiter punctuation/whitespace only). */
  readonly clause: string;
  /** Code identifiers named in `clause` itself (explicitCodeIdentifiers-style rules — see `explicitIdentifiersIn`). */
  readonly subjectIdentifiers: readonly string[];
  /** Normalised concept words: EN lowercase stems; JA bridged via jaGlossary. */
  readonly subjectTerms: readonly string[];
  /** True when `clause` named no identifier of its own and inherited the lead clause's subject identifiers (its own concept terms, if any, are still unioned in — see module doc "Facet-only clause"). */
  readonly inheritedFromLead: boolean;
  /**
   * P0-1: "A.b"/"A::b"/"A#b" pairs named in `clause` (or inherited from the
   * lead), capped at 2 — see `qualifiedMemberPairsIn`. The bare owner name
   * is never, by itself, the focal of a facet that names one of its
   * members. OPTIONAL (defaults to `[]` at every read site) so an existing
   * `FacetRequirement` object literal built by another test/module before
   * this field existed keeps compiling unchanged.
   */
  readonly qualifiedMembers?: readonly QualifiedMemberPair[];
  /**
   * P1-8: non-code-shaped candidate words sitting in the clause's own
   * identifier slot (lowercase Latin-with-diacritics, bare CJK), capped at
   * 4 — see `weakSubjectCandidatesIn`. Verified against real declarations
   * only by the caller; this module is fs-free. OPTIONAL for the same
   * back-compatibility reason as `qualifiedMembers` above.
   */
  readonly subjectWeakCandidates?: readonly string[];
  /**
   * Names the clause writes in CALL syntax (`quote()`, `estimate(cart)`; never
   * a method called on an object) — see `callShapedNamesIn`. The clause's own
   * when it writes any; otherwise the lead sentence's, exactly when
   * `inheritedFromLead`. Absent when empty. resolveFacetFocal tries these
   * against workspace DECLARATIONS before every identifier tier, so a value
   * question's explicit callable outranks an identifier the question only
   * carries as data (Copilot retest r2, 2026-10-02).
   */
  readonly subjectCallables?: readonly string[];
}

// ---------------------------------------------------------------------------
// Change-request gate — a CHANGE request yields no requirement at all.
// ---------------------------------------------------------------------------
//
// "Explain the retry conditions" asks what IS true; "fix the retry
// conditions" asks for something to become different. Facets describe what
// an ANSWER must show, so a change-request clause mints nothing (never even
// inherits the lead's subject). Checked PER CLAUSE (not per whole query) so
// one imperative clause in a composite request does not suppress a
// genuinely separate question elsewhere in the same query.
//
// A clause is a change request only when its MAIN verb is an edit verb
// (orchestrator, 2026-09-27 integration review of round 3): an English
// clause-initial imperative, optionally after a politeness or intent lead
// ("please", "can you", "I want to", "let's", "I'm going to", "we need
// to"), or a Japanese edit verb in a request/intent form (…して / …したい /
// …してほしい / …をお願い / …する予定, a change plan …案 / …方針, a sentence-final
// te-form request, a sentence-final 〜にして). An edit word that is only the
// SUBJECT MATTER of a question or an explanation request ("walk me through
// how the cache is updated", 「キャッシュに追加されるまでの流れ」, 「変更履歴」,
// "which bug fix", "raises SomeError") never makes its clause a change
// request — matching an edit word anywhere in the clause did, and needed a
// growing list of noun guards to stay usable.
const EDIT_VERB_EN =
  "(?:fix(?:es|ed|ing)?|renam(?:e|es|ed|ing)|refactor(?:s|ed|ing)?|add(?:s|ed|ing)?|remov(?:e|es|ed|ing)|delet(?:e|es|ed|ing)|" +
  "implement(?:s|ed|ing)?|chang(?:e|es|ed|ing)|increas(?:e|es|ed|ing)|decreas(?:e|es|ed|ing)|rais(?:e|es|ed|ing)|lower(?:s|ed|ing)?|" +
  "bump(?:s|ed|ing)?|replac(?:e|es|ed|ing)|swap(?:s|ped|ping)?|updat(?:e|es|ed|ing)|modif(?:y|ies|ied|ying)|mov(?:e|es|ed|ing)|" +
  "mak(?:e|es|ing)|set(?:s|ting)?|comment(?:s|ed|ing)?\\s+out|append(?:s|ed|ing)?|insert(?:s|ed|ing)?|rewrit(?:e|es|ing)|" +
  "revert(?:s|ed|ing)?|convert(?:s|ed|ing)?|migrat(?:e|es|ed|ing)|disabl(?:e|es|ed|ing)|enabl(?:e|es|ed|ing)|patch(?:es|ed|ing)?|" +
  "writ(?:e|es|ing)|creat(?:e|es|ed|ing)|introduc(?:e|es|ed|ing)|extract(?:s|ed|ing)?|wir(?:e|es|ed|ing)\\s+up|hook(?:s|ed|ing)?\\s+up)";
const CHANGE_LEAD_EN =
  "(?:(?:and|also|then|so)\\s+)*(?:(?:please|pls|kindly)\\s+)?" +
  "(?:(?:can|could|would|will)\\s+you\\s+(?:please\\s+)?(?:also\\s+)?|let['’]?s\\s+|go\\s+ahead\\s+and\\s+|help\\s+me\\s+|" +
  "i\\s+(?:want|need|would\\s+like)\\s+(?:you\\s+)?to\\s+|i['’]?d\\s+like\\s+(?:you\\s+)?to\\s+|we\\s+(?:should|need\\s+to|must|have\\s+to)\\s+|" +
  "i['’]?m\\s+(?:going\\s+to\\s+|about\\s+to\\s+)?|i\\s+am\\s+(?:going\\s+to\\s+|about\\s+to\\s+)?|i\\s+(?:will|['’]ll)\\s+)?";
const CHANGE_REQUEST_EN_RE = new RegExp(`^\\s*${CHANGE_LEAD_EN}${EDIT_VERB_EN}\\b`, "i");
// …して is a request unless it continues as a progressive/resultative
// (している / してる / してあ… / しており): 「実装している箇所」 asks where something
// is implemented, 「実装して」 asks for an implementation.
const EDIT_NOUN_JA = "(?:修正|変更|追加|削除|リファクタ(?:リング)?|追記|書き換え|置き換え|差し替え|更新|実装|改修|置換|挿入|移動|リネーム|名前変更|無効化|有効化|作成)";
const CHANGE_REQUEST_JA_RE = new RegExp(
  `${EDIT_NOUN_JA}(?:を)?(?:して(?!い|る|あ|おり|おる)|したい|をお願い|お願い|する予定|しよう|案|方針|計画|プラン)` +
    "|(?:変え|直し|加え|入れ|消し|書い|足し|外し|抜い|削っ)て(?:ください|下さい|ほしい|欲しい|もらえ\\S*|くれ\\S*)?\\s*(?:[。！!？?]|$)" +
    "|引き(?:上げ|下げ)(?:て|たい|る予定)" +
    "|(?:に|く)して(?:ください|下さい|ほしい|欲しい)?\\s*(?:[。！!？?]|$)" +
    "|するようにして",
);

function isChangeClause(clause: string): boolean {
  return CHANGE_REQUEST_EN_RE.test(clause) || CHANGE_REQUEST_JA_RE.test(clause);
}

// ---------------------------------------------------------------------------
// FIX-FAB item 8 (eval-0927 review #19) — a NEGATED instruction not to
// change something ("do not change/modify/touch the callers", 「呼び出し元は
// 変更しないでください」) is a CONSTRAINT on a future edit, never a request for
// information: the same non-facet status `isChangeClause` already gives an
// AFFIRMATIVE change request, extended to its negation. Checked per clause.
// ---------------------------------------------------------------------------
const NEGATED_INSTRUCTION_EN_RE =
  /\b(?:do\s+not|don['’]?t|never)\b(?:\s+\w+){0,3}?\s+(?:change|modify|touch|alter|edit|rename|remove|delete|break)\b/i;
const NEGATED_INSTRUCTION_JA_RE = new RegExp(
  `${EDIT_NOUN_JA}(?:は|を)?しないで(?:ください|下さい)?` +
    `|${EDIT_NOUN_JA}(?:は|を)?しないよう(?:に(?:して(?:ください|下さい)?)?)?` +
    "|触(?:れ|ら)?ないで(?:ください|下さい)?",
);

/** Exported for requestItems.ts, whose topic items must not treat the same constraint as a search target. */
export function isNegatedInstructionClause(clause: string): boolean {
  return NEGATED_INSTRUCTION_EN_RE.test(clause) || NEGATED_INSTRUCTION_JA_RE.test(clause);
}

// P1-10 (round-4/5 fable finding, callersNegatedParen): a negated
// instruction commonly rides as its own PARENTHETICAL inside a larger
// clause ("Who calls fetchWithRetry (do not change it)?") rather than as
// its own top-level clause -- `splitClauses` already isolates the
// comma/"and"-joined case (`callersNegatedSameSentence`'s "please do not
// modify anything" lands in its own clause and is correctly dropped by
// `isNegatedInstructionClause` above), but testing the WHOLE clause here
// and dropping it outright silently discarded the REAL question the
// parenthetical was merely attached to. Strips ONLY a parenthetical
// sub-span that ITSELF reads as a negated instruction (an equal-length
// neutral filler, mirroring this module's own `stripGuardedSpans` -- never
// removed, so offsets elsewhere are undisturbed); a parenthetical that is
// not itself a negated instruction (a normal aside) is left untouched. ASCII
// and full-width parens both count -- Japanese prose commonly uses the
// full-width forms （…） the same way English uses (…).
const PARENTHETICAL_RE = /[(（][^()（）]*[)）]/g;

function stripNegatedInstructionParentheticals(clause: string): string {
  return clause.replace(PARENTHETICAL_RE, (m) => (isNegatedInstructionClause(m) ? " ".repeat(m.length) : m));
}

// ---------------------------------------------------------------------------
// Documentation-existence guard — asking IF a document exists is not asking
// for the thing the document would show (held-out en-45/ja-n4: "Is there a
// document that shows the processing flow as a diagram?" / "処理の流れを図にした
// ドキュメントはありますか？" both lexically contain a flow trigger but are asking
// about DOCUMENTATION, not requesting the flow itself).
// ---------------------------------------------------------------------------
// FIX-FAB item 8 (eval-0927 review #9, adversarialDoesExist800): the
// original `does .* exist` alternative and the trailing `[\s\S]*?` gap were
// BOTH unbounded, so a pathological "does exist "-repeated input degenerated
// into O(n^2) backtracking (measured 3.4 s at 800 repeats, 21.9 s at 1600).
// Bounded to a fixed-width window, same style as every other facet regex in
// this file (`[^.?!]{0,N}?`): a clause is already sentence/clause-split
// before this runs, so a real "is there a document that shows X" question
// never needs more than a few dozen characters of gap either side.
const DOC_EXISTENCE_EN_RE =
  /\b(?:is there|do (?:we|you) have|does\b(?:[^.?!]){0,30}?\bexist)\b(?:[^.?!]){0,40}?\b(?:document|docs?|diagram|guide|readme|page)\b/i;
const DOC_EXISTENCE_JA_RE = /(?:ドキュメント|資料|図)[^。]*(?:あります|ある)/;

function isDocumentationExistenceClause(clause: string): boolean {
  return DOC_EXISTENCE_EN_RE.test(clause) || DOC_EXISTENCE_JA_RE.test(clause);
}

// ---------------------------------------------------------------------------
// Negative-guard compounds — a positive trigger word inside one of these
// spans never fires. Stripped (replaced by an equal-length neutral filler,
// never removed, so surrounding offsets/other matches are undisturbed)
// BEFORE any positive pattern runs.
// ---------------------------------------------------------------------------
const VALUE_NEGATIVE_GUARDS: readonly RegExp[] = [
  /\bdefault\s+exports?\b/gi,
  /\bdefault\s+branch(?:es)?\b/gi,
  /\bdefault\s+cases?\b/gi,
  /\bdefault\s+constructors?\b/gi,
  /\bvalue\s+objects?\b/gi,
  /\bkey-values?\b/gi,
  /\breturn\s+values?\b/gi,
  // FIX-FACET-R round 2 (held-out3 c-en-35/c-ja-29): "value proposition" uses
  // "value" in a business/pitch sense, never a code-value question; デフォルト
  // ブランチ ("default branch") is the JA mirror of the existing EN
  // default-branch guard above -- the bare "デフォルト" trigger below cannot
  // itself see it is part of this compound.
  /\bvalue\s+propositions?\b/gi,
  /デフォルトエクスポート/g,
  /値オブジェクト/g,
  /戻り値/g,
  /デフォルトブランチ/g,
  // held-out4 d-ja-20: 返り値 ("return value") is an alternative common
  // spelling of 戻り値 above (返り and 戻り are both ordinary readings of
  // "return"/"give back") -- same guard, same reasoning, different kanji.
  /返り値/g,
  // Copilot retest (2026-10-02): "compute" naming a KIND of resource (a
  // compute shader/node/cluster) never asks for a computed value -- the
  // guard keeps VALUE_COMPUTED_IMPERATIVE_EN_RE below off it.
  /\bcompute\s+(?:shaders?|nodes?|instances?|clusters?|units?|engines?|resources?|budgets?|capacity)\b/gi,
];

function stripGuardedSpans(text: string, guards: readonly RegExp[]): string {
  let out = text;
  for (const guard of guards) out = out.replace(guard, (m) => "□".repeat(m.length));
  return out;
}


