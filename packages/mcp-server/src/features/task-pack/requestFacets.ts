// condition: condition(s) / criteria / criterion / rule(s) [for] / under what
// circumstances / in which case(s) / "when <aux> …" — NOT when the verb is
// called/invoked/used/triggered (that is callers: "when is X called" asks
// for a call site, not a condition). Bare rule(s) (held-out en-41: "the
// retry rules") generalizes "rule(s) for" to the same concept without the
// preposition. JA: 条件/判定条件/判定基準/基準/どのような場合/どんな場合.
// ---------------------------------------------------------------------------
const CONDITION_BARE_EN_RE = /\bconditions?\b|\bcriteria\b|\bcriterion\b|\brules?\b/i;
// held-out2 b-en-17: bare "under which" -- not only "...circumstances" /
// "...conditions" -- already implies a conditional/situational question
// whatever noun follows ("under which indexing modes"); a general
// preposition+relative frame, not tied to any noun.
const CONDITION_CIRCUMSTANCE_EN_RE =
  /\bunder\s+what\s+circumstances\b|\bin\s+which\s+cases?\b|\bunder\s+wh(?:ich|at)\s+conditions?\b|\bunder\s+which\b/i;
// held-out2 b-en-08/b-en-21: "what makes/causes/triggers/determines/decides
// X (to be) Y" is the trigger-frame mirror of "under what conditions" --
// asking WHAT PRODUCES an outcome/eligibility is a condition question even
// with no "condition"/"when" word in the sentence at all. held-out3 c-en-25
// widens the gap to allow a SUBJECT NOUN between "what" and the verb ("what
// threshold number TRIGGERS ..."), not only the verb immediately after
// "what" -- still anchored on "what" as the very first word of the phrase.
const CONDITION_TRIGGER_VERB_EN_RE = /\bwhat\s+(?:\w+\s+){0,3}?(?:makes|causes|triggers|determines|decides)\b/i;
// held-out3 c-en-25's second clause: "at what <noun> does ... kick in" is
// the threshold-frame mirror of the trigger-verb frame above -- a general
// "the point at which behavior changes" question.
const CONDITION_THRESHOLD_EN_RE = /\bat\s+what\b[^.?!]{0,40}?\bkicks?\s+in\b/i;
// held-out4 d-en-26/d-en-25/round-3 category 4: "what MUST BE TRUE (about|
// for) X" is a requirement frame -- the general "what's the precondition"
// question; "does it APPLY BEFORE OR AFTER Y" asks about ordering relative
// to another rule, itself a condition on when a rule takes effect; "under
// what STATE" is the same "under what X" shape as CONDITION_CIRCUMSTANCE_EN_RE
// with a different noun.
const CONDITION_MUST_BE_TRUE_EN_RE = /\bmust\s+be\s+true\b/i;
const CONDITION_APPLY_BEFORE_AFTER_EN_RE = /\bappl(?:y|ies)\s+before\s+or\s+after\b/i;
const CONDITION_STATE_EN_RE = /\bunder\s+what\s+state\b/i;
const WHEN_AUX_RE = /\bwhen\b\s+(?:do|does|did|is|are|was|were|will|would|can|could|should)\b/i;
const WHEN_CALLERS_VERB_RE = /\bwhen\s+(?:do|does|did|is|are|was|were)\s+(?:\w+\s+){0,4}?(?:is\s+|are\s+)?(?:called|invoked|used|triggered)\b/i;
// held-out2 b-ja-21: トリガー/きっかけ ("trigger"/"the thing that sets it off") is
// the JA mirror of CONDITION_TRIGGER_VERB_EN_RE above. held-out3 additions:
// どんなとき/どんな時/どういうとき/どういう時/どのようなとき/どのような時 generalize
// どんな場合/どのような場合 above past 場合 ("case") to とき ("when/moment"), the
// same "under what X" question with a different noun; 判断が入る/判定する/
// 分岐する are decision-point frames ("where does the branch/judgment
// happen"); 閾値/しきい値 ("threshold") is the JA mirror of a threshold BEING
// the condition boundary itself (c-ja-25: no explicit 条件/とき/トリガー word,
// but "at what threshold does X happen" is definitionally a condition ask,
// same reasoning as the EN threshold frame below).
// held-out4 additions: どういうケース/どんなケース (the JA mirror of "in which
// case(s)" with a different noun); どんな状態なら/どういう状態で (requirement/state
// frames, the JA mirror of "under what state"); どちらで適用 ("which [of the
// two orderings] does it apply under", the JA mirror of "apply before or
// after").
const CONDITION_JA_RE =
  /条件|判定条件|判定基準|基準|どのような場合|どんな場合|トリガー|きっかけ|どんなとき|どんな時|どういうとき|どういう時|どのようなとき|どのような時|判断が入る|判定する|分岐する|閾値|しきい値|どういうケース|どんなケース|どんな状態なら|どういう状態で|どちらで適用/;
// held-out2 b-ja-17: どの<名詞>で + a PLAIN passive verb (…される) is the JA
// mirror of the bare "under which" frame above -- "under which mode does X
// get overridden". Deliberately narrower than a bare どの<名詞>で (which
// false-positives on an ordinary "which status code" SELECTION question,
// e.g. held-out set #1's ja-02 "どのステータスコードで再試行が発生しますか" --
// "発生します", a plain active verb, never matches …される): the plain
// passive される is the general grammatical marker that distinguishes "under
// which X does Y happen TO something" from "with which X" alone.
//
// held-out4 d-ja-18 (precision): どのタイミングで…される ("at what POINT IN THE
// PROCESS does X happen") matches this same shape but is a FLOW/timing
// question (see FLOW_JA_RE's どのタイミングで entry), not a configuration/
// situational condition like どのモードで/どのインデックスモードで above -- the
// negative lookahead excludes タイミング specifically so the two questions
// land on their own facet, never both.
const CONDITION_JA_WHICH_RE = /どの(?!タイミング)[^\s、。!?！？]{1,12}で.{0,15}?される/;
// FIX-FACET-R: 条件付き ("conditional compilation") uses 条件 as a modifier of
// a build-flag noun, not a question about a condition/predicate -- held-out2
// b-ja-33's false positive. リトリガー/再トリガー ("re-trigger", a retry/flow
// noun) contains トリガー as a substring but names an action, not "what
// triggers X" -- held-out2 b-ja-15's false positive (the bare トリガー added
// to CONDITION_JA_RE above cannot itself see "リ"/"再" as a prefix, since JS
// `\b` does not mark a boundary between two non-ASCII-word characters).
const CONDITION_NEGATIVE_GUARDS: readonly RegExp[] = [/条件付き/g, /リトリガー|再トリガー/g];

function isConditionClause(guardedClause: string): boolean {
  if (WHEN_AUX_RE.test(guardedClause) && !WHEN_CALLERS_VERB_RE.test(guardedClause)) return true;
  return CONDITION_BARE_EN_RE.test(guardedClause)
    || CONDITION_CIRCUMSTANCE_EN_RE.test(guardedClause)
    || CONDITION_TRIGGER_VERB_EN_RE.test(guardedClause)
    || CONDITION_THRESHOLD_EN_RE.test(guardedClause)
    || CONDITION_MUST_BE_TRUE_EN_RE.test(guardedClause)
    || CONDITION_APPLY_BEFORE_AFTER_EN_RE.test(guardedClause)
    || CONDITION_STATE_EN_RE.test(guardedClause)
    || CONDITION_JA_RE.test(guardedClause)
    || CONDITION_JA_WHICH_RE.test(guardedClause);
}

