async function selectedProfile(query: string): Promise<{ selected: string | undefined; reason: string }> {
  const root = makeWorkspace(os.tmpdir(), "bind");
  const result = await buildTaskPack({ query }, root);
  return { selected: result.profile_binding?.selected, reason: result.profile_binding?.reason ?? "" };
}

