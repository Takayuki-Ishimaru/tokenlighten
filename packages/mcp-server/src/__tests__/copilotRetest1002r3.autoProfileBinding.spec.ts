describe("one call, no task.profile: the whole closure on the first hop (live wire, the env `tl workspace setup` writes for VS Code)", () => {
  // .vscode/mcp.json's env for the vscode client (packages/cli workspace.ts
  // serverConfig): the turn-economy umbrella and the VS Code advertisement profile.
  const VSCODE_ENV: Readonly<Record<string, string>> = {
    TOKENLIGHTEN_CLIENT: "vscode",
    TOKENLIGHTEN_CLIENT_ID: "vscode",
    TL_TURN_ECONOMY: "1",
    TOKENLIGHTEN_TASK_PACK_MAX_BYTES: "0",
  };
  const saved = new Map<string, string | undefined>();
  beforeEach(() => {
    for (const [key, value] of Object.entries(VSCODE_ENV)) {
      saved.set(key, process.env[key]);
      process.env[key] = value;
    }
  });
  afterEach(() => {
    for (const [key, value] of saved) {
      if (value === undefined) delete process.env[key];
      else process.env[key] = value;
    }
    saved.clear();
  });

  async function firstHop(query: string): Promise<Record<string, any>> {
    const ws = makeWorkspace(HOME, "wire");
    const response = await callTool("tl_read_file", { query, task: { epoch: "new" }, cwd: ws });
    const text = response.content[0]?.type === "text" ? response.content[0].text : "{}";
    return JSON.parse(text) as Record<string, any>;
  }

  function servedText(body: Record<string, any>): string {
    return (Array.isArray(body["evidence"]) ? body["evidence"] : [])
      .map((entry: any) => (typeof entry?.body === "string" ? entry.body : ""))
      .join("\n");
  }

  it.each([
    ["r3 live large-task paraphrase", R3_LIVE_QUERY, QUOTE_MARKERS],
    ["r3 repeat paraphrase", R3_REPEAT_QUERY, QUOTE_MARKERS],
    ["r3 small-task prompt", R3_SMALL_QUERY, RETRY_MARKERS],
    ["compute <call> for <input>", COMPUTE_RETRY_QUERY, RETRY_MARKERS],
  ])("%s: answer profile, act.answer, every marker served", async (_label, query, markers) => {
    const body = await firstHop(query);
    const summary = JSON.stringify({
      profile: body["profile"],
      binding: body["profile_binding"],
      decision: body["decision"]?.kind,
      evidence: (body["evidence"] ?? []).map((entry: any) => `${entry.path}:${entry.range}`),
    });
    expect(body["profile"], summary).toBe("answer");
    expect(body["decision"]?.kind, summary).toBe("act.answer");
    const served = servedText(body);
    for (const marker of markers) expect(served, `"${marker}" missing: ${summary}`).toContain(marker);
  }, 60_000);
});
