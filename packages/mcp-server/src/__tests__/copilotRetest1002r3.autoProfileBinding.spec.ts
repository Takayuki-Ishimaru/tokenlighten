function makeWorkspace(base: string, tag: string): string {
  const ws = fs.realpathSync(shortTmpDir(base, `.tl-r3pb-${tag}-`));
  tmpDirs.push(ws);
  const files: Record<string, string> = {
    "package.json": "{\"name\":\"r3pb\",\"private\":true,\"type\":\"module\"}\n",
    ...COPILOT_CHECKOUT_FILES,
    ...COPILOT_RETRY_FILES,
  };
  for (let i = 0; i < 18; i++) files[`src/unrelated${i}.ts`] = `export function unrelated${i}(value: number): number {\n  return value + ${i};\n}\n`;
  for (const [rel, content] of Object.entries(files)) {
    const abs = path.join(ws, rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content, "utf8");
  }
  return ws;
}

